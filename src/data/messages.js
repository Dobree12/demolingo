// --- Helper: Get random message from array ---
export function getRandomMessage(arr) {
  return arr[Math.floor(Math.random() * arr.length)];
}

// --- Helper: Get correct message with variable reward intensity ---
export function getCorrectMessage() {
  const roll = Math.random();
  if (roll < 0.1) return getRandomMessage(correctMessages.high);
  if (roll < 0.4) return getRandomMessage(correctMessages.medium);
  return getRandomMessage(correctMessages.low);
}

// --- Helper: Get lesson complete message based on score ---
export function getLessonCompleteMessage(score) {
  if (score === 100) return getRandomMessage(lessonCompleteMessages.perfect);
  if (score >= 85) return getRandomMessage(lessonCompleteMessages.great);
  if (score >= 70) return getRandomMessage(lessonCompleteMessages.good);
  return getRandomMessage(lessonCompleteMessages.okay);
}
